package io.github.shijianjs.kmp.reflect.proxy

import io.github.shijianjs.kmp.reflect.KmpClass
import io.github.shijianjs.kmp.reflect.KmpClasses
import io.github.shijianjs.kmp.reflect.KmpFunction
import io.github.shijianjs.kmp.reflect.KmpReflectException
import kotlin.reflect.KClass

/**
 * Receives every call made through a dynamic proxy.
 *
 * @see KmpProxy.create
 */
public fun interface KmpInvocationHandler {
    /**
     * Answers one call.
     *
     * @param proxy the proxy instance the call arrived on; passing it to another proxied call is safe.
     * @param function the reflected function being called, so implementations can switch on
     * [KmpFunction.name] and read parameter names.
     * @param args the arguments in declaration order.
     * @return the value the proxy's member should return; `Unit` for a `Unit`-returning member.
     */
    public fun invoke(proxy: Any?, function: KmpFunction, args: List<Any?>): Any?
}

/**
 * Creates dynamic proxies for reflected interfaces.
 *
 * The proxy class is generated by the KSP processor for every `@KmpReflect` interface: unlike
 * `java.lang.reflect.Proxy` it exists as ordinary Kotlin code, so it works on every target this
 * library supports. Resolving the interface's metadata picks the generated class:
 *
 * ```kotlin
 * val greeter = KmpProxy.create<Greeter> { _, function, args -> "hi ${args[0]}" }
 * ```
 */
public object KmpProxy {
    /**
     * Creates a proxy implementing [T] and routes every call to [handler].
     *
     * @throws KmpReflectException when [T] is not a registered interface with a generated proxy.
     */
    public inline fun <reified T : Any> create(handler: KmpInvocationHandler): T =
        create(T::class, handler)

    /**
     * Creates a proxy implementing [type] and routes every call to [handler].
     *
     * @throws KmpReflectException when [type] is not a registered interface with a generated proxy.
     */
    @Suppress("UNCHECKED_CAST")
    public fun <T : Any> create(type: KClass<T>, handler: KmpInvocationHandler): T =
        KmpClasses.of(type).newProxy(handler) as T

    /**
     * Creates a proxy for this class's interface.
     *
     * @throws KmpReflectException when this is not an interface, or when no proxy class was generated.
     */
    public fun create(kmpClass: KmpClass, handler: KmpInvocationHandler): Any = kmpClass.newProxy(handler)
}
